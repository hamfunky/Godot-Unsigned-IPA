"""Bake the approved front desk cashier (prototype v4, Hamza 19 Oct) into part textures for the Godot rig.
  c_body         legs + pumps + neck + wrap dress + waist tie (no arms: the rig draws them so they can count)
  c_head         head + bun + hair + glasses (pivot = chin, so the rig can tilt it)
  c_head_blink   eyes shut
  c_head_happy   happy closed eyes + open smile (cheer)
Arms (skin capsules + dress-coloured cap sleeves) + hands + the notes are drawn in code by scripts/cashier_rig.gd.
Writes <proj>/assets/game/sprites/cashier/*.png and <proj>/scripts/cashier_parts.gd.
Run: python3 tools/char/cashier_parts.py <project>     (Playwright + Chromium, Pillow)
"""
import sys, os, io
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cashier as C, detailer as D
from PIL import Image
from playwright.sync_api import sync_playwright

PROJ = sys.argv[1] if len(sys.argv) > 1 else "."
OUT = os.path.join(PROJ, "assets/game/sprites/cashier")
RES = 1.5
VB = (-130, -50, 260, 360)


def render(pg, body):
    pg.set_content(f'<html><body style="margin:0;background:transparent">{D.svg(body, VB[2], VB[3], VB)}</body></html>')
    return Image.open(io.BytesIO(pg.locator("svg").screenshot(omit_background=True))).convert("RGBA")


def crop_save(img, name, pivot, pad=2):
    l, t, r, b = img.split()[3].getbbox()
    l, t = max(0, l - pad), max(0, t - pad)
    r, b = min(img.width, r + pad), min(img.height, b + pad)
    img.crop((l, t, r, b)).save(os.path.join(OUT, name + ".png"), optimize=True)
    px, py = (pivot[0] - VB[0]) * RES, (pivot[1] - VB[1]) * RES
    return (round(px - l, 2), round(py - t, 2))


def main():
    os.makedirs(OUT, exist_ok=True)
    L = C.layout()
    chin = (0.0, L["chin"])
    parts = {}
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(device_scale_factor=RES, viewport={"width": VB[2], "height": VB[3]})
        parts["c_body"] = crop_save(render(pg, "".join(C.body(L))), "c_body", (0.0, D.GROUND))
        parts["c_head"] = crop_save(render(pg, C.head(L, "smile")), "c_head", chin)
        D.BLINK = True
        parts["c_head_blink"] = crop_save(render(pg, C.head(L, "smile")), "c_head_blink", chin)
        D.BLINK = False
        parts["c_head_happy"] = crop_save(render(pg, C.head(L, "cheer")), "c_head_happy", chin)
        b.close()
    S, sy = C.V["S"], L["sy"]
    gd = ['extends RefCounted',
          '## GENERATED by tools/char/cashier_parts.py from the approved cashier (prototype v4, 19 Oct). Don\'t edit.',
          '## Textures: res://assets/game/sprites/cashier/<name>.png. Units = design units (feet at y = GROUND).',
          '',
          'const GROUND := %.1f' % D.GROUND,
          'const RES := %.2f' % RES,
          'const CHIN := Vector2(0.0, %.1f)' % L["chin"],
          'const SHOULDER := Vector2(%.1f, %.1f)   # right shoulder (x mirrors for the left)' % (S - 7, sy + 20),
          'const UPPER := 36.0',
          'const FORE := 34.0',
          'const TOP := -24.0          # top of the bun',
          'const SKIN := [Color("%s"), Color("%s")]' % C.SKIN,
          'const DRESS := [Color("%s"), Color("%s"), Color("%s")]' % C.DRESS,
          'const NAILS := Color("%s")' % C.LIPS[0],
          'const PARTS := {']
    for k, v in parts.items():
        gd.append('\t"%s": Vector2(%.2f, %.2f),' % (k, v[0], v[1]))
    gd.append('}')
    with open(os.path.join(PROJ, "scripts/cashier_parts.gd"), "w") as fh:
        fh.write("\n".join(gd) + "\n")
    print("baked", list(parts))


if __name__ == "__main__":
    main()
